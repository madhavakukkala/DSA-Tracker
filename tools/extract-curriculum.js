// One-off extraction (§1): reads dsa-dev-roadmap.html, evaluates the PHASES/W
// script block, verifies the counts, and writes src/data/curriculum.json plus
// src/data/curriculum.js (the same data as a classic-script global, because
// fetch() of local JSON is blocked on file:// URLs).
//
// Run:  node tools/extract-curriculum.js
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const html = fs.readFileSync(path.join(root, "dsa-dev-roadmap.html"), "utf8");

// Weekly problem targets from the workbook's 32-Week Plan sheet (column "Target").
const TARGETS = [
  16, 18, 18, 16, 16, 14, 15, 15, 15, 14, 14, 12, 16, 14, 13, 12,
  14, 13, 16, 15, 14, 15, 13, 13, 13, 14, 15, 12, 14, 20, 20, 12,
];

// Find the script block that defines the data (not the render code).
const blocks = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => m[1]);
const dataBlock = blocks.find(b => b.includes("const W ="));
if (!dataBlock) throw new Error("Could not find the PHASES/W script block");

const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(dataBlock + "\nthis.PHASES = PHASES; this.W = W;", sandbox);
const { PHASES, W } = sandbox;

// ---- verify (§1) ----
const fail = msg => { throw new Error("VERIFY FAILED: " + msg); };
if (PHASES.length !== 8) fail("expected 8 phases, got " + PHASES.length);
if (W.length !== 32) fail("expected 32 weeks, got " + W.length);
for (let p = 1; p <= 8; p++) {
  const n = W.filter(w => w.ph === p).length;
  if (n !== 4) fail("phase " + p + " has " + n + " weeks, expected 4");
}
let weekdayEntries = 0, sundayEntries = 0;
for (const w of W) {
  if (!Array.isArray(w.d) || w.d.length !== 6) fail("week " + w.n + " has " + (w.d || []).length + " weekdays");
  for (const [i, day] of w.d.entries()) {
    if (!Array.isArray(day) || day.length !== 3) fail("week " + w.n + " day " + (i + 1) + " lacks 3 entries");
    for (const s of day) {
      if (typeof s !== "string" || !s.trim()) fail("week " + w.n + " day " + (i + 1) + " has an empty entry");
    }
    weekdayEntries++;
  }
  if (!Array.isArray(w.sun) || w.sun.length !== 2) fail("week " + w.n + " Sunday lacks 2 entries");
  for (const s of w.sun) {
    if (typeof s !== "string" || !s.trim()) fail("week " + w.n + " Sunday has an empty entry");
  }
  sundayEntries++;
}
if (weekdayEntries !== 192) fail("expected 192 weekday entries, got " + weekdayEntries);
if (sundayEntries !== 32) fail("expected 32 Sunday entries, got " + sundayEntries);
if (TARGETS.length !== 32) fail("expected 32 targets");

const curriculum = {
  phases: PHASES.map(p => ({ p: p.p, title: p.title, when: p.when })),
  weeks: W.map(w => ({
    n: w.n, ph: w.ph, dates: w.dates, step: w.step,
    dsa: w.dsa, dev: w.dev, goal: w.goal,
    target: TARGETS[w.n - 1],
    d: w.d, sun: w.sun,
  })),
};

const outDir = path.join(root, "src", "data");
fs.mkdirSync(outDir, { recursive: true });
const json = JSON.stringify(curriculum, null, 1);
fs.writeFileSync(path.join(outDir, "curriculum.json"), json + "\n");
fs.writeFileSync(
  path.join(outDir, "curriculum.js"),
  "// GENERATED by tools/extract-curriculum.js — do not edit by hand.\n" +
  "window.SEED = window.SEED || {};\n" +
  "window.SEED.curriculum = " + json + ";\n"
);
console.log("OK: 32 weeks, 8 phases, 192 weekday entries x3, 32 Sundays x2 — 224 days total.");
console.log("Wrote src/data/curriculum.json and src/data/curriculum.js");
